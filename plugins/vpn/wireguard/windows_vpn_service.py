# Populated by _init_runtime(); module import must not touch the filesystem.
LOG_FILE: str = ""
logger = logging.getLogger("ResistineVPN")


def _init_runtime(regenerate_token: bool = False) -> None:
    """Initialize on-disk state (config dir, IPC token, log handlers).

    Called from SvcDoRun() (regenerate_token=True — the service mints a fresh
    token on every start, H1) and the __main__ guard (read-only token path) —
    *never* at import time so this module remains safe to import on
    macOS/Linux (e.g. by tests). Safe to call multiple times.
    """
    global IPC_TOKEN, LOG_FILE

    try:
        os.makedirs(CONFIG_BASE, exist_ok=True)
    except OSError:
        pass

    if regenerate_token:
        IPC_TOKEN = _create_ipc_token()
    elif not IPC_TOKEN:
        IPC_TOKEN = _read_ipc_token()

    if not LOG_FILE:
        LOG_FILE = _get_log_file()
        # Only attach a file handler once.
        if not any(
            isinstance(h, logging.FileHandler)
            and getattr(h, "baseFilename", None) == LOG_FILE
            for h in logger.handlers
        ):
            handler = logging.FileHandler(LOG_FILE)
            handler.setFormatter(
                logging.Formatter(
                    "%(asctime)s | %(levelname)s | %(funcName)s:%(lineno)d | %(message)s",
                ),
            )
            logger.addHandler(handler)
            logger.setLevel(logging.DEBUG)
            logger.info(f"Service module loaded. Logging to: {LOG_FILE}")


# ---------------- Helpers ----------------

def run_cmd(cmd: list, timeout: int = 30) -> subprocess.CompletedProcess:
    return subprocess.run(
        cmd,
        capture_output=True,
        text=True,
        timeout=timeout,
        creationflags=subprocess.CREATE_NO_WINDOW,
    )


def wg_service_name(tunnel: str) -> str:
    return f"WireGuardTunnel${tunnel}"


def _flush_dns_cache() -> None:
    """Flush the Windows DNS resolver cache after tunnel state changes."""
    def _flush():
        try:
            subprocess.run(
                ["ipconfig", "/flushdns"],
                capture_output=True, timeout=10,
                creationflags=subprocess.CREATE_NO_WINDOW,
            )
            logger.debug("DNS cache flushed")
        except Exception:
            logger.debug("DNS cache flush failed (non-critical)")
    threading.Thread(target=_flush, daemon=True).start()


# ---------------- Config discovery ----------------

def find_config(tunnel: str, config_path: str = None) -> str | None:
    """
    Find tunnel config file.
    Priority:
    1. Explicit path from GUI (user AppData)
    2. ProgramData fallback
    """
    if config_path and os.path.exists(config_path):
        logger.info(f"Using provided config: {config_path}")
        return config_path

    fallback = os.path.join(CONFIG_BASE, f"{tunnel}.conf")
    if os.path.exists(fallback):
        logger.info(f"Using ProgramData config: {fallback}")
        return fallback

    logger.warning(f"No config found for tunnel '{tunnel}'")
    return None


def find_default_tunnel() -> str | None:
    """
    Discover default tunnel from ProgramData.
    Prefers 'phoenix' (then the pre-rebrand 'resistine'), otherwise first .conf found.
    """
    if not os.path.exists(CONFIG_BASE):
        return None

    confs = [f for f in os.listdir(CONFIG_BASE) if f.endswith(".conf")]
    if not confs:
        logger.warning(f"No .conf files in {CONFIG_BASE}")
        return None

    for preferred in ("phoenix", "resistine"):
        if f"{preferred}.conf" in confs:
            return preferred

    name = confs[0].replace(".conf", "")
    logger.info(f"Auto-detected tunnel: {name}")
    return name


# ---------------- WireGuard helpers ----------------

def uninstall_tunnel(tunnel: str):
    svc = wg_service_name(tunnel)
    result = run_cmd(["sc", "query", svc])
    if "1060" in (result.stdout + result.stderr):
        return True, "Not installed"

    run_cmd(["sc", "stop", svc])
    time.sleep(1)

    result = run_cmd([WIREGUARD_EXE, "/uninstalltunnelservice", tunnel])
    logger.info(f"Uninstall '{tunnel}': returncode={result.returncode}")
    time.sleep(1)
    return True, "Uninstalled"


def _scan_config_for_script_hooks(content: str, tunnel: str) -> bool:
    """Return True if the config content carries a WireGuard script hook."""
    for line in content.splitlines():
        key = line.split("=", 1)[0].strip().lower()
        if key in SCRIPT_HOOK_KEYS:
            logger.error(
                f"Refusing config with script hook '{key}' for '{tunnel}'"
            )
            return True
    return False


def _ensure_system_config(tunnel: str, source_conf: str) -> str | None:
    """
    Copy the config to ProgramData so the SYSTEM-level WireGuard tunnel
    service can read it, regardless of where the GUI stored the original.

    WireGuard's /installtunnelservice registers a service that runs as
    SYSTEM.  SYSTEM has no access to any user's %APPDATA%, so if the .conf
    lives there the tunnel silently fails to start.  Copying to ProgramData
    (CONFIG_BASE) fixes this while keeping the user's copy untouched.

    Returns the path that should be passed to /installtunnelservice, or
    None when the config must NOT be installed (unreadable, carries script
    hooks, or its secret-bearing ProgramData copy could not be secured).
    Callers must treat None as a hard failure (M1).

    SECURITY (M2, TOCTOU): the source is read exactly ONCE into memory; the
    hook scan runs on that in-memory content and the very same content is
    what gets written to the system path (atomic temp + os.replace). The
    source file is never re-read, so it cannot be swapped between the scan
    and the copy.
    """
    system_conf = os.path.join(CONFIG_BASE, f"{tunnel}.conf")

    # Single read (M2) — everything below operates on this snapshot only.
    try:
        with open(source_conf, "r", encoding="utf-8", errors="replace") as fh:
            content = fh.read()
    except OSError as e:
        logger.error(f"Cannot read config for '{tunnel}': {e}")
        return None

    # Refuse configs carrying script hooks: WireGuard-for-Windows won't run
    # them without DangerousScriptExecutionAllowed, but a SYSTEM service
    # should never install one regardless of registry state. This scan runs
    # for EVERY source — including a config already sitting in ProgramData
    # (M1): the old shortcut path skipped the scan entirely.
    if _scan_config_for_script_hooks(content, tunnel):
        return None  # hard failure — install_tunnel refuses to proceed

    # Already in ProgramData — scanned above, nothing to copy.
    if os.path.abspath(source_conf) == os.path.abspath(system_conf):
        return system_conf

    try:
        os.makedirs(CONFIG_BASE, exist_ok=True)
        # Write the scanned in-memory content (never shutil.copy2 of the
        # source, which would re-read a potentially swapped file) to a
        # private temp file, lock its ACL, then atomically move it in place.
        fd, tmp_path = tempfile.mkstemp(
            dir=CONFIG_BASE, prefix=f".{tunnel}.", suffix=".tmp"
        )
        try:
            # The .conf contains the WireGuard PrivateKey; ProgramData's
            # default DACL grants BUILTIN\Users read. Lock the temp file to
            # SYSTEM+Administrators BEFORE the key material lands in it.
            if not _restrict_file_acl(tmp_path):
                logger.error("Could not restrict config ACL — refusing install")
                os.close(fd)
                fd = -1
                try:
                    os.remove(tmp_path)
                except OSError:
                    pass
                return None
            os.write(fd, content.encode("utf-8"))
        finally:
            if fd >= 0:
                os.close(fd)
        os.replace(tmp_path, system_conf)
        logger.info(
            f"Copied config for '{tunnel}' to ProgramData: {system_conf}"
        )
    except Exception as e:
        logger.error(
            f"Could not stage config in ProgramData for '{tunnel}': {e}"
        )
        return None

    return system_conf


def install_tunnel(tunnel: str, config_path: str = None):
    conf = find_config(tunnel, config_path)
    if not conf:
        return False, f"Config not found for tunnel: {tunnel}"

    if not os.path.exists(WIREGUARD_EXE):
        return False, f"WireGuard not installed at {WIREGUARD_EXE}"

    # FIX (VPN not starting): WireGuard tunnel services run as SYSTEM and
    # cannot read files from a user's %APPDATA%.  Always install from a
    # ProgramData copy so the SYSTEM account can access the config.
    conf = _ensure_system_config(tunnel, conf)
    if conf is None:
        # Hard failure (M1): the config is unreadable, carries script hooks
        # (PreUp/PostUp/PreDown/PostDown), or could not be securely staged.
        msg = (
            f"Config for tunnel '{tunnel}' was rejected: unreadable, "
            f"contains script hooks, or could not be securely staged"
        )
        logger.error(msg)
        return False, msg

    uninstall_tunnel(tunnel)

    result = run_cmd([WIREGUARD_EXE, "/installtunnelservice", conf])
    logger.debug(f"Install '{tunnel}': returncode={result.returncode}")
    logger.debug(f"stdout: {result.stdout.strip()}")
    logger.debug(f"stderr: {result.stderr.strip()}")

    if "already installed" in result.stderr.lower():
        return True, "Already installed"

    if result.returncode == 0:
        logger.info(f"Tunnel '{tunnel}' installed")
        time.sleep(1)
        return True, "Installed"

    logger.error(f"Failed to install '{tunnel}': {result.stderr}")
    return False, result.stderr.strip()


def start_tunnel(tunnel: str):
    svc = wg_service_name(tunnel)
    logger.info(f"Starting: {svc}")

    result = run_cmd(["sc", "start", svc])
    combined = (result.stdout + result.stderr).lower()

    if "already running" in combined:
        return True, "Already running"
    if "start_pending" in combined or result.returncode == 1056:
        return True, "Starting"
    if result.returncode == 0:
        return True, "Started"

    logger.error(f"Failed to start '{tunnel}': {result.stderr}")
    return False, result.stderr.strip()


def stop_tunnel(tunnel: str):
    result = run_cmd(["sc", "stop", wg_service_name(tunnel)])
    combined = (result.stdout + result.stderr).lower()

    if "not started" in combined or "1062" in combined:
        return True, "Already stopped"

    return result.returncode == 0, combined.strip()


def status_tunnel(tunnel: str) -> str:
    result = run_cmd(["sc", "query", wg_service_name(tunnel)])
    out = (result.stdout + result.stderr).lower()

    if "1060" in out or "does not exist" in out:
        return "Not Installed"
    if "running" in out:
        return "Running"
    if "start_pending" in out:
        return "Starting"
    if "stop_pending" in out:
        return "Stopping"
    if "stopped" in out:
        return "Stopped"

    logger.warning(f"Unknown status for '{tunnel}': {out.strip()}")
    return "Unknown"


# ---------------- IPC Handler ----------------

# GUI configs live in %APPDATA%\{Phoenix,Resistine}\wireguard (see
# utils/settings.get_config_dir + vpn_functions_windows). The service runs
# standalone (no utils import), so recognize any local user's Roaming dir.
_USER_APPDATA_WG_RE = re.compile(
    r"^[A-Za-z]:\\Users\\[^\\/:*?\"<>|]+\\AppData\\Roaming\\"
    r"(?:Phoenix|Resistine)\\wireguard$",
    re.IGNORECASE,
)


def _allowed_config_dirs() -> list[str]:
    """Directories a caller-supplied config path may live in."""
    dirs = [os.path.abspath(CONFIG_BASE)]
    appdata = os.environ.get("APPDATA")
    if appdata:
        for app in ("Phoenix", "Resistine"):
            dirs.append(os.path.abspath(os.path.join(appdata, app, "wireguard")))
    return dirs


def _is_unc_path(path: str) -> bool:
    return path.startswith("\\\\") or path.startswith("//")


def _validated_config_path(tunnel: str, config_path) -> str | None:
    """Confine the caller-supplied config path.

    The IPC peer is any local process that knows the token, and this service
    runs as SYSTEM — so a raw path here is an arbitrary-file-read/copy
    primitive, and merely *resolving* a UNC path (\\\\attacker\\share\\x.conf)
    leaks the machine account's NTLM hash (L2). Require: not a UNC path, a
    real file whose basename matches the (already-validated) tunnel name, and
    a resolved location inside a known config directory — the user's AppData
    wireguard dir or CONFIG_BASE/ProgramData. Everything else falls back to
    the ProgramData copy for that tunnel.
    """
    if not config_path or not isinstance(config_path, str):
        return None

    # Reject UNC / network paths outright, before any filesystem touch.
    if _is_unc_path(config_path):
        logger.warning("Rejecting UNC/network config_path")
        return None

    path = os.path.abspath(config_path)
    if _is_unc_path(path):
        logger.warning("Rejecting UNC/network config_path")
        return None

    if (not os.path.isfile(path)
            or os.path.basename(path) != f"{tunnel}.conf"):
        logger.warning("Rejecting config_path outside the expected shape")
        return None

    # The containing directory must be one of the known config locations
    # (this also pins the path to local fixed-drive letters — no \\?\ or
    # device namespaces, no foreign drives).
    parent = os.path.normcase(os.path.dirname(path))
    for base in _allowed_config_dirs():
        if parent == os.path.normcase(base):
            return path
    if _USER_APPDATA_WG_RE.fullmatch(os.path.dirname(path)):
        return path

    logger.warning("Rejecting config_path outside the known config directories")
    return None


def handle_request(request: dict) -> dict:
    # Constant-time comparison; a non-string token or an unset IPC_TOKEN is
    # rejected outright (compare_digest raises TypeError on non-strings).
    supplied = request.get("token")
    if (not isinstance(supplied, str) or not IPC_TOKEN
            or not hmac.compare_digest(supplied, IPC_TOKEN)):
        return {"status": "error", "message": "Unauthorized"}

    cmd         = request.get("command")
    tunnel      = request.get("tunnel")

    if cmd not in ALLOWED_COMMANDS:
        return {"status": "error", "message": f"Invalid command: {cmd}"}

    if not tunnel:
        return {"status": "error", "message": "Missing tunnel"}

    # The tunnel name is interpolated into service names and ProgramData
    # paths by a SYSTEM process — reject separators, "..", flag-like names.
    if not is_valid_config_name(tunnel):
        return {"status": "error", "message": "Invalid tunnel name"}

    config_path = _validated_config_path(tunnel, request.get("config_path"))

    try:
        if cmd == "status":
            return {"status": "ok", "state": status_tunnel(tunnel)}

        if cmd == "connect":
            state = status_tunnel(tunnel)
            if state == "Running":
                return {"status": "ok", "state": "Running", "message": "Already running"}

            # Always reinstall before starting — even if the tunnel service
            # exists in "Stopped" state. A stopped WireGuardTunnel$ service
            # means it previously failed (often exit code 2 = config not found
            # because SYSTEM couldn't read AppData). Reinstalling copies the
            # config to ProgramData via _ensure_system_config so SYSTEM can
            # access it. Skipping install for "Stopped" is the root cause of
            # the default/first config silently failing to connect.
            ok, msg = install_tunnel(tunnel, config_path)
            if not ok:
                return {"status": "error", "state": status_tunnel(tunnel), "message": msg}

            ok, msg = start_tunnel(tunnel)
            actual_state = status_tunnel(tunnel)
            if actual_state in ("Running", "Starting"):
                _flush_dns_cache()
                return {"status": "ok", "state": actual_state, "message": msg}
            return {"status": "error", "state": actual_state, "message": msg}

        if cmd == "disconnect":
            state = status_tunnel(tunnel)
            if state in ("Stopped", "Not Installed"):
                return {"status": "ok", "state": "Stopped", "message": "Already stopped"}
            ok, msg = stop_tunnel(tunnel)
            actual_state = status_tunnel(tunnel)
            if ok:
                _flush_dns_cache()
            return {"status": "ok" if ok else "error", "state": actual_state, "message": msg}

        if cmd == "start":
            ok, msg = start_tunnel(tunnel)
            return {"status": "ok" if ok else "error", "message": msg}

        if cmd == "stop":
            ok, msg = stop_tunnel(tunnel)
            return {"status": "ok" if ok else "error", "message": msg}

        if cmd == "restart":
            stop_tunnel(tunnel)
            time.sleep(1)
            ok, msg = start_tunnel(tunnel)
            actual_state = status_tunnel(tunnel)
            return {"status": "ok" if ok else "error", "state": actual_state, "message": "Restarted"}

        if cmd == "health":
            return {
                "status":    "ok",
                "service":   "running",
                "socket":    "listening",
                "wireguard": status_tunnel(tunnel),
            }

    except Exception as e:
        logger.exception(f"Error handling '{cmd}': {e}")
        return {"status": "error", "message": str(e)}

    return {"status": "error", "message": "Unhandled command"}


# ---------------- Socket Server ----------------

def _recv_request(conn: socket.socket) -> bytes:
    """Read one newline-terminated JSON request from the socket.

    SECURITY/CORRECTNESS (L3): a single recv() can return a fragment of the
    request (TCP gives no message boundaries), which would mis-parse or
    reject legitimate requests. Read until a newline terminator (sent by
    service_client), peer FIN, or a per-connection timeout (compat with
    older clients that send no terminator), with a hard total cap.
    """
    conn.settimeout(RECV_TIMEOUT_SECONDS)
    buf = b""
    while b"\n" not in buf:
        try:
            chunk = conn.recv(RECV_BUFFER)
        except socket.timeout:
            break  # old client without newline framing: parse what we have
        if not chunk:
            break
        buf += chunk
        if len(buf) > MAX_REQUEST_BYTES:
            raise ValueError("Request too large")
    return buf


def _handle_connection(conn: socket.socket) -> None:
    """Handle a single IPC connection in its own thread."""
    try:
        data = _recv_request(conn)
        if not data:
            return
        request = json.loads(data.decode("utf-8"))
        response = handle_request(request)
        conn.sendall(json.dumps(response).encode("utf-8"))
    except Exception as e:
        logger.error(f"Request error: {e}")
        try:
            conn.sendall(
                json.dumps({"status": "error", "message": str(e)}).encode("utf-8")
            )
        except Exception:
            pass
    finally:
        conn.close()


def socket_server(stop_event):
    servicemanager.LogInfoMsg("IPC socket thread starting")
    time.sleep(0.2)

    sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    # SECURITY (H2): never set SO_REUSEADDR here. On Windows it would let any
    # other local process bind (hijack/squat) 127.0.0.1:51888 and harvest the
    # IPC token from connecting GUI clients. SO_EXCLUSIVEADDRUSE makes the
    # bind exclusive so no other socket can share the port.
    # NOTE: port-based auth is inherently weaker than it should be — a
    # challenge-response handshake (token never sent on the wire) or a named
    # pipe with an explicit DACL is the stronger follow-up.
    if hasattr(socket, "SO_EXCLUSIVEADDRUSE"):
        sock.setsockopt(socket.SOL_SOCKET, socket.SO_EXCLUSIVEADDRUSE, 1)

    try:
        sock.bind((SERVICE_HOST, SERVICE_PORT))
        sock.listen(5)
        sock.settimeout(1.0)
        servicemanager.LogInfoMsg(f"IPC listening on {SERVICE_HOST}:{SERVICE_PORT}")
    except Exception as e:
        servicemanager.LogErrorMsg(f"Socket bind failed: {e}")
        logger.error(f"Socket bind failed: {e}")
        return

    while win32event.WaitForSingleObject(stop_event, 0) != win32con.WAIT_OBJECT_0:
        try:
            conn, _ = sock.accept()
        except socket.timeout:
            continue
        except Exception as e:
            logger.error(f"Accept error: {e}")
            break

        threading.Thread(
            target=_handle_connection, args=(conn,), daemon=True
        ).start()

    sock.close()
    servicemanager.LogInfoMsg("IPC socket thread stopped")


def run_socket_server(stop_event):
    try:
        socket_server(stop_event)
    except Exception as e:
        servicemanager.LogErrorMsg(f"Socket server crashed: {repr(e)}")
        logger.exception("Socket server crashed")


