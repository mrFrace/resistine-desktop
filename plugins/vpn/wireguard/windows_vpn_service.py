IPC_TOKEN: str = ""


# Grantees must be plain account names — never groups like "Users" or
# "Everyone" (an attacker-planted %USERNAME% could otherwise widen the grant),
# and never contain icacls metacharacters.
_SAFE_GRANTEE_RE = re.compile(r"^[A-Za-z0-9._-]{1,104}$")

_DENY_GRANTEES = {"users", "everyone", "authenticated users", "guests", "interactive"}


def _restrict_file_acl(path: str, extra_read_user: str | None = None) -> bool:
    """Lock a secret file's ACL to SYSTEM + Administrators (plus, optionally,
    one named user with read access) and strip inheritance.

    Returns True only when icacls reports success — callers treat False as
    fatal for secret material (the ProgramData default DACL grants
    BUILTIN\\Users read, which must never apply to the IPC token or to
    tunnel configs containing the WireGuard private key).
    """
    if sys.platform != "win32":
        return True
    cmd = [
        "icacls", path,
        "/inheritance:r",
        "/grant", "*S-1-5-18:F",          # SYSTEM (SID form: locale-proof)
        "/grant", "*S-1-5-32-544:F",      # BUILTIN\Administrators
    ]
    if extra_read_user:
        if (not _SAFE_GRANTEE_RE.fullmatch(extra_read_user)
                or extra_read_user.lower() in _DENY_GRANTEES):
            logging.getLogger("ResistineVPN").error(
                "Refusing ACL grant to suspicious account name")
            return False
        cmd += ["/grant", f"{extra_read_user}:R"]
    try:
        result = subprocess.run(
            cmd,
            check=False,
            capture_output=True,
            timeout=5,
            # Suppress the console window so icacls doesn't flash a cmd
            # window when the service runs in a user session (debug mode).
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
        )
        return result.returncode == 0
    except Exception:
        return False


def _restrict_token_acl(token_path: str) -> bool:
    """Restrict the IPC token file's ACL. Fail-closed: see caller."""
    import getpass

    user = os.environ.get("USERNAME") or getpass.getuser()
    # Under the SYSTEM service USERNAME is the machine account; the grant is
    # then harmless (machine$ gets read). The GUI heals the ACL for the
    # interactive user when it reads the token from its own session.
    return _restrict_file_acl(token_path, extra_read_user=user)


def _read_ipc_token() -> str:
    """Read-only token access for non-service callers (CLI helpers, debug).

    Never creates a token file and never treats a short/garbage file as a
    valid token; the token is owned by the running service and regenerated
    by it on every start (see _create_ipc_token). Returns "" when unavailable.
    """
    try:
        with open(IPC_TOKEN_FILE, "r") as fh:
            token = fh.read().strip()
        if len(token) >= 32:
            return token
    except OSError:
        pass
    return ""


def _create_ipc_token() -> str:
    """Generate a fresh IPC token for this service process and persist it.

    SECURITY (H1): a pre-existing token file must NEVER be trusted. Any
    local user who pre-plants %PROGRAMDATA%\\Resistine\\wireguard\\.ipc_token
    before the first service start would otherwise know the token and fully
    control this SYSTEM service. The service therefore regenerates the token
    on every start: delete whatever is on disk, create the file exclusively
    (O_CREAT | O_EXCL, so a racing attacker-created file fails the create
    instead of being silently reused), lock its ACL, then write the token.
    The token only needs to live as long as the service process.
    """
    log = logging.getLogger("ResistineVPN")

    token = _secrets.token_hex(32)
    try:
        os.makedirs(os.path.dirname(IPC_TOKEN_FILE), exist_ok=True)
        # Remove any pre-planted/stale file; ignore "already missing".
        try:
            os.remove(IPC_TOKEN_FILE)
        except FileNotFoundError:
            pass
        except OSError as e:
            log.error("Could not remove stale IPC token file: %s", e)
            return token  # in-memory token only; GUI auth fails loudly

        # Exclusive create: fails if anything re-appears between the remove
        # and this open (symlink/hardlink plants included).
        fd = os.open(IPC_TOKEN_FILE, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
        try:
            # Lock the ACL *before* the secret is written so there is no
            # window in which the token bytes sit under the permissive
            # ProgramData default DACL.
            if not _restrict_token_acl(IPC_TOKEN_FILE):
                # Fail closed: a token readable by BUILTIN\Users is the key
                # to a SYSTEM service. Better no persisted token (GUI auth
                # fails loudly) than a world-readable one.
                log.error("Could not restrict IPC token ACL — token not persisted")
                os.close(fd)
                fd = -1
                try:
                    os.remove(IPC_TOKEN_FILE)
                except OSError:
                    pass
                return token
            os.write(fd, token.encode("ascii"))
        finally:
            if fd >= 0:
                os.close(fd)
    except OSError as e:
        log.error("Could not persist IPC token: %s", e)
    return token


def _find_wireguard_exe() -> str:
    """Locate the WireGuard executable, checking both Program Files paths."""
    candidates = [
        r"C:\Program Files\WireGuard\wireguard.exe",
        r"C:\Program Files (x86)\WireGuard\wireguard.exe",
    ]
    for path in candidates:
        if os.path.exists(path):
            return path
    # Fallback to PATH lookup
    found = shutil.which("wireguard")
    if found:
        return found
    # Return the default path so error messages are meaningful
    return candidates[0]


WIREGUARD_EXE = _find_wireguard_exe()


