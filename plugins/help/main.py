import os
import sys
import webbrowser

from PyQt6.QtCore import QUrl
from PyQt6.QtGui import QTextCursor, QTextFormat
from PyQt6.QtWidgets import (
    QComboBox,
    QHBoxLayout,
    QTextBrowser,
    QVBoxLayout,
    QWidget,
)

from gui.page_kit import PAGE_MAX_WIDTH, PageHeader, hairline, icon_button
from plugins.base_plugin import BasePlugin
from utils.logger import logger

_DIR = os.path.dirname(os.path.realpath(__file__))

# Root files (shipped in the app bundle root) to add to the dropdown alongside
# the user docs in docs/. LICENSE-3rd-Party.md is the human-readable SBOM /
# third-party attribution generated by scripts/sbom/generate_sbom.py. The
# developer README.md is intentionally excluded — it's a build guide, not help.
_ROOT_FILES = ["LICENSE.md", "LICENSE-3rd-Party.md"]

# Structural box-drawing characters that mark ASCII-art diagram lines.
# Deliberately excludes arrows (→ ← ▼ ▲) and em-dash, which appear inline
# in normal prose.
_BOX_CHARS = set("│┌┐└┘├┤┬┴┼═║╔╗╚╝")


def _fence_ascii_art(text: str) -> str:
    """Wrap bare box-drawing diagrams in code fences.

    Several docs paste ASCII diagrams directly into the markdown without a
    ``` fence; Qt then renders them as proportional-font paragraphs with
    collapsed whitespace — unreadable garbage. Runs of 2+ consecutive lines
    containing structural box-drawing characters (outside existing fences)
    get fenced so they render as monospace code blocks.
    """
    lines = text.split("\n")
    out: list[str] = []
    in_fence = False
    run: list[str] = []

    def flush():
        if len(run) >= 2:
            out.append("```")
            out.extend(run)
            out.append("```")
        else:
            out.extend(run)
        run.clear()

    for line in lines:
        if line.lstrip().startswith("```"):
            flush()
            in_fence = not in_fence
            out.append(line)
        elif not in_fence and any(c in _BOX_CHARS for c in line):
            run.append(line)
        else:
            flush()
            out.append(line)
    flush()
    return "\n".join(out)


def _resource_path(relative_path: str) -> str:
    if hasattr(sys, "_MEIPASS"):
        return os.path.join(sys._MEIPASS, relative_path)
    return os.path.join(
        os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))),
        relative_path,
    )


class Plugin(BasePlugin):
    """Help plugin."""

    defer_reveal_until_settled = True

    def __init__(self, app):
        super().__init__(
            id="009", version="2025.01.01", order=1010, name="Help",
            status=None,
            description="Guides and answers for using Phoenix.",
            supported_systems=["Windows", "Linux", "Mac"],
            translations={"US": "Help", "ES": "Ayuda", "FR": "Aide"},
            icon_light_path=os.path.join(_DIR, "help_light.png"),
            icon_dark_path=os.path.join(_DIR, "help_dark.png"),
            uninstall_enabled=False,
        )
        self.app = app
        self.docs_dir = _resource_path("docs")
        self.history: list[str] = []
        self.current_index = -1
        self.home_file = None
        self.current_dir = self.docs_dir

    # ===================================================================
    #  UI
    # ===================================================================
    def create_main_screen(self):
        # Not a scroll_page: the browser scrolls the document itself, so the
        # header and navigation stay put.
        page = QWidget()
        outer = QHBoxLayout(page)
        outer.setContentsMargins(48, 36, 48, 32)
        outer.setSpacing(0)
        column = QWidget()
        column.setObjectName("Transparent")
        column.setMaximumWidth(PAGE_MAX_WIDTH)
        col = QVBoxLayout(column)
        col.setContentsMargins(0, 0, 0, 0)
        col.setSpacing(0)
        outer.addWidget(column, 1)
        outer.addStretch(0)  # left-align the column on wide windows

        header = PageHeader("Help", self._subtitle())
        self.back_button = icon_button("chevron-left", "Back")
        self.back_button.setEnabled(False)
        self.back_button.clicked.connect(self.go_back)
        header.add_control(self.back_button)

        self.home_button = icon_button("house", "Home")
        self.home_button.clicked.connect(self.go_home)
        header.add_control(self.home_button)

        self.help_files = self.get_help_files()
        self.file_dropdown = QComboBox()
        self.file_dropdown.setMinimumWidth(180)
        self.file_dropdown.setToolTip("Help topic")
        self.file_dropdown.addItems(self.help_files)
        self.file_dropdown.activated.connect(
            lambda _i: self.navigate_to_file(self.file_dropdown.currentText()))
        header.add_control(self.file_dropdown)
        col.addWidget(header)

        col.addSpacing(20)
        col.addWidget(hairline())
        col.addSpacing(8)

        # --- Content ---
        self.browser = QTextBrowser()
        self.browser.setOpenLinks(False)
        self.browser.anchorClicked.connect(self._on_anchor_clicked)
        col.addWidget(self.browser, 1)

        # Load the home file (docs/Help.md), like the original.
        self.load_file(os.path.join(self.docs_dir, "Help.md"))
        return page

    @staticmethod
    def _subtitle() -> str:
        text = "Guides, release notes and licences"
        try:
            from utils.updates.version import get_current_version
            version = get_current_version()
        except Exception:
            version = ""
        if version and version != "0.0.0":
            text += f" · Phoenix {version}"
        return text

    # ===================================================================
    #  File listing / navigation
    # ===================================================================
    def get_help_files(self):
        files = []
        if self.docs_dir:
            project_root = os.path.dirname(os.path.abspath(self.docs_dir))
            for f in _ROOT_FILES:
                if os.path.exists(os.path.join(project_root, f)):
                    files.append(f)
        if self.docs_dir and os.path.exists(self.docs_dir):
            for file in os.listdir(self.docs_dir):
                if file.endswith(".md"):
                    files.append(file)
        return sorted(set(files))

    def navigate_to_file(self, filename):
        if not filename:
            return
        project_root = os.path.dirname(os.path.abspath(self.docs_dir))
        root_path = os.path.join(project_root, filename)
        if os.path.exists(root_path) and filename in _ROOT_FILES:
            self.load_file(root_path)
        else:
            file_path = os.path.join(self.docs_dir, filename)
            if os.path.exists(file_path):
                self.load_file(file_path)

    def go_home(self):
        if self.home_file and os.path.exists(self.home_file):
            self.load_file(self.home_file, add_to_history=True)

    def go_back(self):
        if self.current_index > 0:
            self.current_index -= 1
            self.load_file(self.history[self.current_index], add_to_history=False)
            self._update_nav_buttons()

    def _update_nav_buttons(self):
        self.back_button.setEnabled(self.current_index > 0)

    def load_file(self, file_path, add_to_history=True):
        self.current_dir = os.path.dirname(os.path.abspath(file_path))
        if self.home_file is None:
            self.home_file = file_path

        if add_to_history:
            if self.current_index < len(self.history) - 1:
                self.history = self.history[: self.current_index + 1]
            self.history.append(file_path)
            self.current_index = len(self.history) - 1
            self._update_nav_buttons()

        if not os.path.exists(file_path):
            self.browser.setMarkdown(
                f"**Error**\n\nFile not found:\n`{file_path}`\n")
            return

        # Reflect the selection in the dropdown.
        filename = os.path.basename(file_path)
        if filename in self.help_files:
            self.file_dropdown.blockSignals(True)
            self.file_dropdown.setCurrentText(filename)
            self.file_dropdown.blockSignals(False)

        try:
            with open(file_path, encoding="utf-8") as f:
                content = f.read()
        except Exception as e:
            self.browser.setMarkdown(f"**Error**\n\n`{e}`")
            return

        if file_path.endswith(".md"):
            self.browser.setMarkdown(_fence_ascii_art(content))
        else:
            # Plain text → render as a code block (mirrors the CTk viewer).
            self.browser.setMarkdown(f"```\n{content}\n```")
        self._harden_code_blocks()

    def _harden_code_blocks(self):
        """Stop fenced code blocks from soft-wrapping.

        Qt's markdown importer emits each code-fence line as its own
        wrappable block, so wide ASCII/box-drawing diagrams reflow into
        garbage at narrow widths. Marking those blocks non-breakable keeps
        every line intact (the browser scrolls horizontally instead).
        """
        doc = self.browser.document()
        cursor = QTextCursor(doc)
        block = doc.begin()
        while block.isValid():
            fmt = block.blockFormat()
            char = block.charFormat()
            # Qt's markdown importer marks code blocks with the fence/language
            # properties and a 'monospace' font family (fixedPitch is NOT set).
            is_code = (
                fmt.hasProperty(QTextFormat.Property.BlockCodeLanguage)
                or fmt.hasProperty(QTextFormat.Property.BlockCodeFence)
                or char.fontFixedPitch()
                or "monospace" in [f.lower() for f in (char.fontFamilies() or [])]
            )
            if is_code and not fmt.nonBreakableLines():
                fmt.setNonBreakableLines(True)
                cursor.setPosition(block.position())
                cursor.setBlockFormat(fmt)
            block = block.next()

    def _on_anchor_clicked(self, url: QUrl):
        target = url.toString()
        logger.info(f"Link clicked: {target}")
        scheme = url.scheme().lower()
        if scheme in ("http", "https", "mailto"):
            webbrowser.open(target)
            return
        if scheme == "file":
            local = url.toLocalFile()
            if os.path.exists(local):
                self.load_file(local)
                return
        # Relative in-doc link → resolve against the current document's dir.
        local = os.path.join(self.current_dir, target)
        if os.path.exists(local):
            self.load_file(local)
        else:
            webbrowser.open(target)
