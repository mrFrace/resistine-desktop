#!/usr/bin/env python3
"""Render the Terms of Service and Privacy Policy for the installers.

docs/Terms.md and docs/Privacy.md are the only place the text is written.
Each installer needs it in its own format, on the screen where the user
agrees before anything is installed:

  packaging/pkg-resources/license.html      macOS .pkg licence pane
  packaging/windows/InstallAgreement.txt    Windows (Inno Setup) licence page
  packaging/linux/AGREEMENT.txt             shipped in /usr/share/doc/phoenix

The outputs are committed, so a build never depends on this script having
run; tests/unit/test_legal.py fails when they are out of date.

    python scripts/build/render_legal.py           # regenerate
    python scripts/build/render_legal.py --check   # exit 1 if stale
"""
from __future__ import annotations

import html
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCES = (ROOT / "docs" / "Terms.md", ROOT / "docs" / "Privacy.md")
LICENSE = ROOT / "LICENSE.md"

PKG_HTML = ROOT / "packaging" / "pkg-resources" / "license.html"
WINDOWS_TXT = ROOT / "packaging" / "windows" / "InstallAgreement.txt"
LINUX_TXT = ROOT / "packaging" / "linux" / "AGREEMENT.txt"

INTRO = (
    "By installing Phoenix you agree to the Terms of Service and the Privacy "
    "Policy below. The application itself is free software under the GNU "
    "General Public License, version 2 or later; its notice follows them."
)

_ASCII = {"→": "->", "·": "-", "—": "-", "–": "-", "‘": "'",
          "’": "'", "“": '"', "”": '"', "…": "...", "‹": "<",
          "©": "(c)"}
_LINK = re.compile(r"\[([^\]]+)\]\(([^)]+)\)")
_BOLD = re.compile(r"\*\*([^*]+)\*\*")
_CODE = re.compile(r"`([^`]+)`")


def _inline_text(s: str) -> str:
    s = _LINK.sub(r"\1", s)
    s = _BOLD.sub(r"\1", s)
    return _CODE.sub(r"\1", s)


def to_text(md: str) -> str:
    """Markdown (the subset these documents use) as plain ASCII text."""
    out = []
    for line in md.splitlines():
        if line.startswith("# "):
            title = _inline_text(line[2:]).upper()
            out += [title, "=" * len(title)]
        elif line.startswith("## "):
            title = _inline_text(line[3:])
            out += [title, "-" * len(title)]
        elif line.startswith("### "):
            out.append(_inline_text(line[4:]) + ":")
        else:
            out.append(_inline_text(line))
    text = "\n".join(out)
    for char, plain in _ASCII.items():
        text = text.replace(char, plain)
    stray = sorted({c for c in text if ord(c) > 127})
    if stray:
        raise SystemExit(f"non-ASCII characters left in the text output: {stray}")
    return text.strip() + "\n"


def _inline_html(s: str) -> str:
    s = html.escape(s, quote=False)
    s = _LINK.sub(r"\1", s)  # the installer pane cannot follow links
    s = _BOLD.sub(r"<strong>\1</strong>", s)
    return _CODE.sub(r"<code>\1</code>", s)


def to_html(md: str) -> str:
    """Markdown (the same subset) as HTML body content, one heading level down."""
    out, in_list, para = [], False, []

    def flush():
        nonlocal para
        if para:
            out.append("<p>" + "<br/>".join(para) + "</p>")
            para = []

    def close_list():
        nonlocal in_list
        if in_list:
            out.append("</ul>")
            in_list = False

    for line in md.splitlines():
        if not line.strip():
            flush()
            close_list()
        elif line.startswith("#"):
            flush()
            close_list()
            level = len(line) - len(line.lstrip("#"))
            out.append(f"<h{level + 1}>{_inline_html(line[level:].strip())}</h{level + 1}>")
        elif line.startswith("- "):
            flush()
            if not in_list:
                out.append("<ul>")
                in_list = True
            out.append(f"<li>{_inline_html(line[2:])}</li>")
        else:
            close_list()
            para.append(_inline_html(line))
    flush()
    close_list()
    return "\n".join(out)


def gpl_notice() -> str:
    """LICENSE.md is the notice as an indented block: unindent it."""
    lines = [ln[4:] if ln.startswith("    ") else ln for ln in LICENSE.read_text(encoding="utf-8").splitlines()]
    return "\n".join(lines).strip()


_PAGE = """<!DOCTYPE html>
<!-- Generated by scripts/build/render_legal.py from docs/Terms.md and
     docs/Privacy.md. Do not edit: change those files and re-run it. -->
<html>
<head>
    <meta charset="utf-8"/>
    <style>
        body {{ font-family: -apple-system, "Helvetica Neue", Helvetica, Arial, sans-serif; font-size: 12px; color: #1d1d1f; margin: 20px 24px; line-height: 1.45; }}
        h1 {{ font-size: 18px; margin: 0 0 10px 0; }}
        h2 {{ font-size: 16px; margin: 22px 0 8px 0; }}
        h3 {{ font-size: 13px; margin: 14px 0 4px 0; color: #424245; }}
        h4 {{ font-size: 12px; margin: 10px 0 2px 0; color: #424245; }}
        p {{ margin: 6px 0; }}
        ul {{ margin: 6px 0; padding-left: 20px; }}
        li {{ margin: 3px 0; }}
        pre {{ white-space: pre-wrap; font-family: inherit; margin: 6px 0; }}
        hr {{ border: 0; border-top: 1px solid #d2d2d7; margin: 20px 0; }}
        @media (prefers-color-scheme: dark) {{
            body {{ color: #f5f5f7; }}
            h3, h4 {{ color: #c7c7cc; }}
            hr {{ border-top-color: #48484a; }}
        }}
    </style>
</head>
<body>
    <h1>Phoenix Agreement</h1>
    <p>{intro}</p>
{body}
    <hr/>
    <h2>Software Licence (GNU GPL)</h2>
    <pre>{gpl}</pre>
</body>
</html>
"""


def render() -> dict[Path, str]:
    docs = [p.read_text(encoding="utf-8") for p in SOURCES]
    body = "\n    <hr/>\n".join(to_html(d) for d in docs)
    page = _PAGE.format(intro=html.escape(INTRO), body=body, gpl=html.escape(gpl_notice(), quote=False))

    rule = "\n" + "=" * 72 + "\n\n"
    gpl_txt = to_text("# Software Licence (GNU GPL)\n\n" + gpl_notice())
    text = "PHOENIX AGREEMENT\n\n" + INTRO + "\n" + rule + rule.join(to_text(d) for d in docs) + rule + gpl_txt
    # Inno Setup shows the file as-is: Windows line endings.
    return {PKG_HTML: page, WINDOWS_TXT: text.replace("\n", "\r\n"), LINUX_TXT: text}


def main(argv: list[str]) -> int:
    stale = []
    for path, content in render().items():
        current = path.read_bytes().decode("utf-8") if path.exists() else None
        if current == content:
            continue
        stale.append(path)
        if "--check" not in argv:
            path.write_bytes(content.encode("utf-8"))
            print(f"wrote {path.relative_to(ROOT)}")
    if "--check" in argv and stale:
        print("out of date (run scripts/build/render_legal.py):")
        for path in stale:
            print(f"  {path.relative_to(ROOT)}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
