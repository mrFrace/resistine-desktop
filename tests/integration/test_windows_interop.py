@pytest.mark.integration
class TestWindowsEdgeCases:
    def test_long_path_config(self, tmp_path, isolated_settings, monkeypatch):
        """Windows has MAX_PATH=260 by default. Config should handle long paths."""
        monkeypatch.setattr("plugins.vpn.wireguard.vpn_functions_windows._settings", isolated_settings)
        # Create a deeply nested path (still under 260 for compatibility)
        # NOTE: the parentheses around ("a" * 50) are necessary.
        # Python evaluates * and / left-to-right with the same precedence
        # when constructing a path like this, so writing
        # `tmp_path / "a" * 50` parses as (tmp_path / "a") * 50 and tries
        # to multiply a Path by an int, which raises an error. This is
        # easy to overlook with any path construction. If you're adding
        # more long-path test cases please be sure that each repeated
        # segment has its own parentheses, otherwise you'll get a
        # TypeError at test time. - Austin
        deep = tmp_path / ("a" * 50) / ("b" * 50) / ("c" * 50)
        deep.mkdir(parents=True)
        monkeypatch.setattr(
            "plugins.vpn.wireguard.vpn_functions_windows.get_writable_wireguard_dir",
            lambda: str(deep),
        )
        isolated_settings.set_secret("vpn", "private_key", "pk=")

        from plugins.vpn.wireguard.vpn_functions_windows import parse_and_create_vpn_config
        config_json = json.dumps({
            "Interface": {"Address": "10.0.0.2"},
            "Peer": {"PublicKey": "srv=", "AllowedIPs": ["0.0.0.0/0"], "Endpoint": "1.2.3.4:51820"},
        })
        path = parse_and_create_vpn_config(config_json)
        assert path is not None
        assert os.path.exists(path)

