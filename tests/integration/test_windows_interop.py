    def test_concurrent_settings_writes(self, isolated_settings):
        """Thread-safe settings must handle concurrent writes without corruption."""
        import threading

        errors = []

        def writer(ns, key, value):
            try:
                for i in range(20):
                    isolated_settings.set(ns, f"{key}_{i}", f"{value}_{i}")
            except Exception as e:
                errors.append(e)

        threads = [
            threading.Thread(target=writer, args=("ns1", "a", "val_a")),
            threading.Thread(target=writer, args=("ns2", "b", "val_b")),
            threading.Thread(target=writer, args=("ns1", "c", "val_c")),  # Same namespace
        ]
        for t in threads:
            t.start()
        for t in threads:
            t.join(timeout=10)

        assert len(errors) == 0
        # Verify data integrity
        for i in range(20):
            assert isolated_settings.get("ns1", f"a_{i}") == f"val_a_{i}"
            assert isolated_settings.get("ns2", f"b_{i}") == f"val_b_{i}"

