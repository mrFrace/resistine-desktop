# ===========================================================================
@pytest.mark.integration
class TestIPCTokenFlow:
    def test_service_token_readable_by_client(self, tmp_path):
        """Token generated by service must be loadable by client."""
        token_file = tmp_path / "Resistine" / "ipc_token"
        token_file.parent.mkdir(parents=True)

        # Service side: generate and write token
        with patch("plugins.vpn.wireguard.windows_vpn_service.IPC_TOKEN_FILE", str(token_file)):
            from plugins.vpn.wireguard.windows_vpn_service import _get_or_create_ipc_token
            service_token = _get_or_create_ipc_token()

        # Client side: read it back
        with patch("plugins.vpn.wireguard.service_client._IPC_TOKEN_FILE", str(token_file)):
            from plugins.vpn.wireguard.service_client import _load_ipc_token
            client_token = _load_ipc_token()

        assert service_token == client_token
        assert len(service_token) == 64

    def test_client_env_override(self):
        """RESISTINE_IPC_TOKEN env var overrides file-based token."""
        with patch.dict(os.environ, {"RESISTINE_IPC_TOKEN": "env_override_token"}):
            with patch("builtins.open", side_effect=FileNotFoundError()):
                from plugins.vpn.wireguard.service_client import _load_ipc_token
                token = _load_ipc_token()
        assert token == "env_override_token"

    def test_client_returns_empty_when_no_token(self):
        """If no token file and no env var, return empty string."""
        env = {k: v for k, v in os.environ.items() if k != "RESISTINE_IPC_TOKEN"}
        with patch.dict(os.environ, env, clear=True):
            with patch("builtins.open", side_effect=FileNotFoundError()):
                from plugins.vpn.wireguard.service_client import _load_ipc_token
                token = _load_ipc_token()
        assert token == ""

    def test_send_command_fails_gracefully_without_token(self):
        """If token is empty, send_command should return error dict, not crash."""
        from plugins.vpn.wireguard.service_client import send_command
        with patch("plugins.vpn.wireguard.service_client._load_ipc_token", return_value=""):
            result = send_command("status", "wg0")
        assert result["status"] == "error"
        assert "token" in result.get("message", "").lower() or "unavailable" in result.get("message", "").lower()


