@pytest.mark.integration
class TestSettingsEncryptionInterop:
    def test_secret_survives_keyring_to_fallback(self, tmp_config_dir, monkeypatch):
        """A secret encrypted with keyring must remain readable when keyring fails
        (same Fernet key in fallback file)."""
        import utils.settings as s

        # Phase 1: Set up with working keyring
        store = {}
        mock_kr = MagicMock()
        mock_kr.get_password.side_effect = lambda svc, user: store.get((svc, user))
        mock_kr.set_password.side_effect = lambda svc, user, pw: store.__setitem__((svc, user), pw)
        mock_kr.get_keyring.return_value = MagicMock(__class__=type("SecureBackend", (), {"__name__": "SecureBackend", "__module__": "keyring.backends.Windows"}))

        monkeypatch.setattr("utils.settings.keyring", mock_kr)

        # Store a secret
        s.set_secret("test", "api_key", "super_secret_123")

        # Verify it's readable
        assert s.get_secret("test", "api_key") == "super_secret_123"

        # Verify the raw value is encrypted
        raw = s.get("test", "api_key")
        assert raw.startswith("ENC:")

    def test_different_namespaces_isolated(self, isolated_settings):
        """Secrets in different namespaces must not interfere."""
        isolated_settings.set_secret("vpn", "key", "vpn_secret")
        isolated_settings.set_secret("wazuh", "key", "wazuh_secret")

        assert isolated_settings.get_secret("vpn", "key") == "vpn_secret"
        assert isolated_settings.get_secret("wazuh", "key") == "wazuh_secret"

    def test_tampered_ciphertext_returns_none(self, isolated_settings):
        """If an encrypted value is corrupted, get_secret must return None."""
        isolated_settings.set("test", "secret", "ENC:corrupted_garbage_data")
        result = isolated_settings.get_secret("test", "secret")
        assert result is None


