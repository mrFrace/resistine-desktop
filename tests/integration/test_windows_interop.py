    def test_status_response_always_has_state_field(self):
        """Tray's _refresh_status reads result.get('state', 'Stopped'). All
        success paths in handle_request return 'state', but error paths may not.
        A missing 'state' on error must default to 'Stopped' or 'disconnected',
        never crash _state_from_service."""
        from plugins.vpn.wireguard.windows_vpn_service import handle_request, IPC_TOKEN
        from gui.tray import _state_from_service

        # Test all known error paths
        error_responses = [
            handle_request({"token": "wrong", "command": "status", "tunnel": "wg0"}),
            handle_request({"token": IPC_TOKEN, "command": "invalid", "tunnel": "wg0"}),
            handle_request({"token": IPC_TOKEN, "command": "status", "tunnel": ""}),
        ]

        for response in error_responses:
            # Tray's _state_from_service handles missing/empty 'state' → 'disconnected'
            tray_state = _state_from_service(response.get("state", "Stopped"))
            assert tray_state in ("connected", "disconnected", "connecting"), (
                f"Error response {response!r} produced invalid tray state: {tray_state}"
            )

    def test_concurrent_settings_secret_writes(self, isolated_settings):
        """Concurrent writes to encrypted settings (e.g. multiple plugins
        saving secrets at once) must not corrupt the encrypted JSON."""
        import threading

        errors = []

        def writer(plugin_name):
            try:
                for i in range(10):
                    isolated_settings.set_secret(plugin_name, f"key_{i}", f"value_{i}")
            except Exception as e:
                errors.append(e)

        threads = [threading.Thread(target=writer, args=(f"plugin_{n}",)) for n in range(4)]
        for t in threads:
            t.start()
        for t in threads:
            t.join(timeout=10)

        assert errors == [], f"Concurrent secret writes caused errors: {errors}"

        # All values must be readable and decrypt correctly
        for n in range(4):
            for i in range(10):
                got = isolated_settings.get_secret(f"plugin_{n}", f"key_{i}")
                assert got == f"value_{i}", (
                    f"plugin_{n}.key_{i} corrupted: got {got!r}"
                )

